/**
 * Example playthrough (deterministic mode). Plays ~12 months as a
 * reasonable CEO through the same service layer the API uses, and writes a
 * narrated log to docs/PLAYTHROUGH.md.
 *
 *   npm run playthrough
 */
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openDb } from '../server/db/connection';
import { loadWorld } from '../server/db/repo';
import { advanceTime, confirmAction, createNewGame, proposeAction } from '../server/game/game';
import { dashboard } from '../server/game/queries';
import { sendMessage, startConversation, submitOffer } from '../server/llm/conversation';
import { NoneProvider } from '../server/llm/provider';
import { fmtEur, mEur } from '../shared/money';

const llm = { provider: new NoneProvider(), timeoutMs: 1000 };
const db = openDb(join(mkdtempSync(join(tmpdir(), 'automanager-play-')), 'play.sqlite'));
createNewGame(db);
const log: string[] = ['# Automanager — example playthrough', '', 'Generated by `npm run playthrough` (deterministic character mode, seed 20270101). Every number below comes from the simulation.', ''];
const say = (s = '') => {
  log.push(s);
  console.log(s);
};
const today = () => loadWorld(db).meta.currentDate;

function act(type: string, payload: unknown, why: string, rationale?: string) {
  const a = proposeAction(db, { type, payload, rationale });
  if (a.status !== 'pending_confirmation') {
    say(`- **${type}** rejected by the validator: ${a.errors.join(' ')}`);
    return a;
  }
  const r = confirmAction(db, a.id, 'ceo', { boardRationale: rationale });
  const money = a.consequences.filter((c) => c.amountCents !== undefined).map((c) => `${c.label}: ${fmtEur(c.amountCents!)}`).join('; ');
  say(`- **${a.summary}** — ${why} → _${r.message}_${money ? ` (${money})` : ''}`);
  return r.action;
}

async function talk(characterId: string, text: string) {
  const conv = startConversation(db, characterId);
  const r = await sendMessage(db, llm, conv.id, text);
  const name = loadWorld(db).characters.find((c) => c.id === characterId)!.name;
  say(`> **CEO → ${name}:** ${text}`);
  say(`> **${name}:** ${r.reply.content}`);
  for (const a of r.actions) say(`>   ↳ proposal: ${a.summary} [${a.status}]`);
  say('');
  return r;
}

function status(title: string) {
  const d = dashboard(db);
  const s = d.forecast?.scenarios[0].summary;
  say(`### ${title} — ${d.meta.currentDate}`);
  say(`Cash ${fmtEur(d.kpis.cashCents)} · liquidity ${fmtEur(d.kpis.liquidityCents)} · revenue YTD ${fmtEur(d.kpis.revenueYtdCents)} · EBIT YTD ${fmtEur(d.kpis.ebitYtdCents)} · net leverage ${d.kpis.netLeverage.toFixed(2)}x · board confidence ${Math.round(d.board.confidence)}`);
  if (s) say(`Forecast (estimate): FY EBIT ${fmtEur(s.fyEbitCents)}, 12-month min liquidity ${fmtEur(s.minLiquidity12mCents)}, Eon SOP ${s.eonSopForecast ?? `blocked (≈${s.eonSopConditional} if supply secured)`}`);
  say('');
}

function advance(days: number) {
  const r = advanceTime(db, days);
  say(`**Advance ${days} days → ${r.to}.** ${r.events.filter((e) => e.severity !== 'info').slice(0, 8).map((e) => e.title).join(' · ') || 'A quiet period.'}`);
  say('');
  return r;
}

async function negotiate(id: string, first: Record<string, number>, message: string) {
  let r = await submitOffer(db, llm, id, first, message);
  say(`- Offer on ${id}: ${JSON.stringify(first)} → **${r.outcome}**`);
  let guard = 0;
  while (r.outcome === 'countered' && guard++ < 5) {
    const n = loadWorld(db).negotiations.find((x) => x.id === id)!;
    const counter = n.rounds[n.rounds.length - 1].terms;
    // Split the difference between our last offer and their counter.
    const mine = n.rounds.filter((x) => x.by === 'ceo').pop()!.terms;
    const mid: Record<string, number> = {};
    for (const t of n.terms) mid[t.key] = Math.round(((mine[t.key] + counter[t.key]) / 2) / t.step) * t.step;
    r = await submitOffer(db, llm, id, guard >= 3 ? counter : mid, 'Let us meet in the middle; we both need this deal.');
    say(`- Counter-round ${guard}: ${JSON.stringify(guard >= 3 ? counter : mid)} → **${r.outcome}**`);
  }
  return r;
}

async function main() {
  say('## January 2027 — first decisions');
  status('Opening position');
  await talk('CHR-HOLM', 'Be frank with me: how much runway do we have, and what worries you most?');
  act('approve_project', { projectId: 'PRJ-VELA-E7' }, 'without it the Vela cannot be sold after 29 Nov 2027');
  act('adjust_production', { lineId: 'LINE-LYON-VELA', plannedDailyRate: 520, reason: 'Align Lyon with retail demand' }, 'stop building unsold Velas');
  act('address_issue', { issueId: 'ISS-KORA-INV', optionKey: 'investigate' }, 'establish facts before spending on a campaign');
  act('address_issue', { issueId: 'ISS-THERMAL', optionKey: 'barrier_redesign' }, 'fix the design, not just test more');
  await talk('CHR-WIERZBICKI', 'I want the electric crossover ready by September. Tell engineering that failure is not an option.');
  say('Negotiating with Voltaris for battery capacity:');
  const v = await negotiate('NEG-VOLTARIS', { dailyVolume: 300, priceEur: 9_200, prepaymentM: 40, takeOrPayPct: 60 }, 'We will commit three years of volume. Hanseatic is ready to qualify an alternative pack if we cannot agree, and our forecast needs 300 packs a day.');
  if (v.outcome === 'accepted') {
    const c = loadWorld(db).contracts.find((x) => x.negotiationId === 'NEG-VOLTARIS' && x.status === 'agreed');
    if (c) act('sign_contract', { contractId: c.id }, 'secures Eon battery supply', 'Secures 300 packs/day for the Eon; prepayment is recovered against invoices.');
  }
  await talk('CHR-OKAFOR', 'I promise you a decision on the Brno hiring plan by 2027-02-20.');
  advance(31);
  status('End of January');

  say('## February–March — people and money');
  act('hire_staff', { departmentId: 'DEP-BRNO', headcount: 450, reason: 'Eon ramp-up' }, 'Brno needs operators before SOP');
  const pr = loadWorld(db).commitments.find((x) => x.promiseeId === 'CHR-OKAFOR' && x.status === 'open');
  if (pr) act('resolve_commitment', { commitmentId: pr.id, outcome: 'fulfilled', note: 'Hiring plan approved.' }, 'kept my word to the CPO');
  say('Wage negotiation with the union:');
  const u = await negotiate('NEG-UNION', { wageIncreasePct: 3.0, oneOffBonusEur: 400, jobGuaranteeMonths: 12 }, 'We can protect jobs at all plants for the length of the agreement; the company cannot afford more than inflation while we fund the Eon.');
  if (u.outcome === 'pending_approval') say('- The union needs a members’ ballot; the answer comes in ~10 days.');
  act('request_financing', { kind: 'bank_term_loan', amountCents: mEur(100), tenorYears: 5, rationale: 'First tranche of the 2028 refinancing' }, 'start refinancing early (board commitment due in April)');
  advance(28);
  const unionDeal = loadWorld(db).contracts.find((x) => x.negotiationId === 'NEG-UNION' && x.status === 'agreed');
  if (unionDeal) act('sign_contract', { contractId: unionDeal.id }, 'peace obligation restored');
  const offer = loadWorld(db).financing.find((f) => f.status === 'offered');
  if (offer) act('accept_financing', { financingId: offer.id }, `bank offered ${fmtEur(offer.offer!.amountCents)}`);
  advance(31);
  status('End of March');
  const inv = loadWorld(db).issues.find((i) => i.id === 'ISS-KORA-INV');
  if (inv && inv.data.rootCause === 'confirmed' && inv.status !== 'resolved') act('address_issue', { issueId: 'ISS-KORA-INV', optionKey: 'service_campaign' }, 'targeted campaign after the root cause was confirmed');

  say('## April–June');
  act('issue_board_proposal', { title: 'Turnaround plan 2027–2029', kind: 'strategy', rationale: 'Secure the Eon launch (battery supply signed, thermal redesign funded), align Vela output with demand, certify Vela to Euro 7, refinance the 2028 notes in tranches starting with a €100m bank loan, and keep liquidity above €700m.', evAlignment: 0.8, growth: 0.4 } as never, 'present the plan to the board');
  advance(30);
  advance(31);
  advance(30);
  status('End of June');

  say('## July–December');
  for (let i = 0; i < 6; i++) {
    const r = advance(31);
    if (r.status !== 'active') break;
  }
  status('Year end');
  const w = loadWorld(db);
  say('## Outcome');
  say(`- Status: ${w.meta.status}${w.meta.terminalReason ? ` — ${w.meta.terminalReason}` : ''}`);
  for (const p of w.projects) say(`- ${p.name}: ${p.status}${p.completedDate ? ` (${p.completedDate})` : ''}, target ${p.targetDate} (original ${p.originalTargetDate})`);
  say(`- Commitments: ${w.commitments.filter((c) => c.status === 'fulfilled').length} kept, ${w.commitments.filter((c) => c.status === 'broken').length} broken, ${w.commitments.filter((c) => ['open', 'due'].includes(c.status)).length} open`);
  say(`- Events recorded: ${(db.prepare('SELECT COUNT(*) AS n FROM events').get() as { n: number }).n}; journal entries: ${(db.prepare('SELECT COUNT(*) AS n FROM journal_entries').get() as { n: number }).n}`);
  mkdirSync('docs', { recursive: true });
  writeFileSync('docs/PLAYTHROUGH.md', log.join('\n'));
  console.log('\nWrote docs/PLAYTHROUGH.md');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
