// Dev helper: drives the running app through a few key interactions and saves screenshots.
import { chromium } from 'playwright';
const base = process.env.BASE ?? 'http://localhost:8790';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
page.on('pageerror', (e) => errors.push(String(e)));
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
await page.goto(`${base}/#/company`);
await page.waitForTimeout(1000);
await page.getByRole('row', { name: /Tomasz Wierzbicki/ }).getByRole('button', { name: 'Meet' }).click();
await page.waitForTimeout(1000);
await page.getByLabel('Your message').fill('I want the electric crossover ready by September. Tell engineering that failure is not an option. Book the external test lab for the thermal tests.');
await page.getByRole('button', { name: 'Send' }).click();
await page.waitForTimeout(2500);
await shot('meeting');
const btn = page.getByRole('button', { name: /Review consequences/ }).first();
if (await btn.count()) {
  await btn.click();
  await page.waitForTimeout(800);
  await shot('review');
  await page.getByRole('button', { name: /Approve & execute|Submit to the board/ }).click();
  await page.waitForTimeout(1500);
}
await page.goto(`${base}/#/projects/PRJ-VELA-E7`);
await page.waitForTimeout(1000);
await page.getByText('Vela Euro 7 compliance').first().click();
await page.waitForTimeout(500);
await page.getByRole('button', { name: 'Approve…' }).click();
await page.waitForTimeout(1000);
await shot('approve-vela');
await page.getByRole('button', { name: /Approve & execute/ }).click();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: '+1 month' }).click();
await page.waitForTimeout(6000);
await shot('briefing');
await page.getByRole('button', { name: 'Continue' }).click();
await page.goto(`${base}/#/inbox/NEG-VOLTARIS`);
await page.waitForTimeout(1200);
await shot('negotiation');
await page.getByRole('button', { name: 'Table this offer' }).click();
await page.waitForTimeout(2500);
await shot('negotiation-after');
await page.goto(`${base}/#/dashboard`);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/dashboard-after.png`, fullPage: true });
console.log('errors', errors);
await browser.close();
