import { mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { openDb } from '../../server/db/connection';
import { loadWorld } from '../../server/db/repo';
import { createNewGame, proposeAction, confirmAction, advanceTime } from '../../server/game/game';

const dir = mkdtempSync(join(process.env.SCRATCH ?? tmpdir(), 'am-'));
const db = openDb(join(dir, 'g.sqlite'));
let t = Date.now();
createNewGame(db);
console.log('new game ms', Date.now() - t);
const w = loadWorld(db);
console.log('loaded', w.meta.currentDate, w.projects.length, 'payables', w.payables.length, 'cash', w.balances['1000'] / 1e8);
const a = proposeAction(db, { type: 'approve_project', payload: { projectId: 'PRJ-VELA-E7' } });
console.log(a.status, a.summary, a.errors, a.consequences.map(c => c.label));
t = Date.now();
const c = confirmAction(db, a.id);
console.log('confirm', c.ok, c.message, Date.now() - t, 'ms');
const b = proposeAction(db, { type: 'adjust_production', payload: { lineId: 'LINE-LYON-VELA', plannedDailyRate: 520 } });
console.log(b.status, b.warnings, b.consequences.map(c => c.label));
console.log(confirmAction(db, b.id).message);
t = Date.now();
const r = advanceTime(db, 40, 'k1');
console.log('advance ms', Date.now() - t, r.from, r.to, r.events.length);
console.log(r.briefing.body);
const r2 = advanceTime(db, 40, 'k1');
console.log('replayed', r2.replayed, r2.to);
const w2 = loadWorld(db);
console.log('after reload', w2.meta.currentDate, 'cash', w2.balances['1000'] / 1e8, 'conf', w2.meta.boardConfidence, w2.meta.lastForecastSummary);
