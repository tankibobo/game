/**
 * Catalogue of projects the CEO can start. Each template has a fixed budget,
 * staffing, milestone plan and completion effects, so strategies (premium,
 * mass-market EV, hybrid transition, cost-down …) have concrete costs, lead
 * times and consequences.
 */
import type { Milestone, Project, ProjectEffect } from '../../shared/domain';
import { addDays, type SimDate } from '../../shared/dates';
import { eur, mEur, type Cents } from '../../shared/money';

export interface ProjectTemplate {
  key: string;
  name: string;
  kind: Project['kind'];
  strategy: string;
  objective: string;
  scope: string;
  sponsorId: string;
  managerId: string;
  departmentId: string;
  fte: number;
  budgetCents: Cents;
  capitalize: boolean;
  priority: Project['priority'];
  linkedModelId: string | null;
  durationDays: number;
  milestones: { name: string; description: string; work: number; externalCents: Cents }[];
  effects: ProjectEffect[];
  risks: Project['risks'];
  acceptanceCriteria: string[];
  /** Template keys of projects this one replaces (a merely proposed one is cancelled when this starts). */
  supersedes?: string[];
  /** Returns a reason when the template cannot be started now. */
  available?: (ctx: { hasActive: (key: string) => boolean; modelStatus: (id: string) => string | undefined }) => string | null;
  tradeoffs: string;
  /** Can it be run again after completion? (Most projects change something once.) */
  repeatable?: boolean;
  /** How stakeholders react when the project starts and when it is delivered. */
  reactions?: { onStart?: Reaction[]; onComplete?: Reaction[] };
  /** Advice the project manager adds to the completion report (what to do to realise the benefit). */
  followUp?: string;
}

/** A stakeholder's reaction: a trust change, an optional morale change and a message to the CEO. */
export interface Reaction {
  characterId: string;
  trust: number;
  subject: string;
  body: string;
  morale?: { departmentId: string; delta: number };
}

